//! Shell completion scripts for bash, zsh, fish and PowerShell.
//!
//! Every script is a pure function of the [`App`] argument table, so a
//! flag cannot be missing from a script without the table missing it
//! too. Two flags live outside the table — the parser answers `--help`
//! and `--version` itself — and are injected from `settings` so a
//! disabled builtin is not offered.
//!
//! The script shapes are contracts the shells read literally: zsh's
//! `_arguments` specs with `[`/`]`/`:` escaped and each entry on its
//! own line; fish's single-quoted words, where a quote is closed,
//! escaped and reopened; bash `case` arms that return before the flag
//! list can overwrite the value they just completed.

use std::string::{String, ToString};
use std::vec::Vec;

use super::app::App;
use super::arg::Arg;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(clippy::enum_variant_names)]
pub enum Shell {
    Bash,
    Zsh,
    Fish,
    PowerShell,
}

impl Shell {
    pub const ALL: [Shell; 4] = [Shell::Bash, Shell::Zsh, Shell::Fish, Shell::PowerShell];

    pub fn from_name(name: &str) -> Option<Self> {
        match name.to_lowercase().as_str() {
            "bash" | "sh" => Some(Shell::Bash),
            "zsh" => Some(Shell::Zsh),
            "fish" => Some(Shell::Fish),
            "powershell" | "pwsh" | "ps1" => Some(Shell::PowerShell),
            _ => None,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Shell::Bash => "bash",
            Shell::Zsh => "zsh",
            Shell::Fish => "fish",
            Shell::PowerShell => "powershell",
        }
    }
}

/// One completable option, flattened off an [`Arg`] so the builtins
/// travel the same path as the declared ones.
struct Opt {
    name: String,
    short: Option<char>,
    long: Option<String>,
    help: String,
    value: bool,
    optional_value: bool,
    repeatable: bool,
    possible: Vec<String>,
    positional: bool,
}

impl Opt {
    /// One of the two flags the parser handles outside the argument
    /// table.
    fn builtin(short: char, long: &str, help: &str) -> Self {
        Opt {
            name: long.to_string(),
            short: Some(short),
            long: Some(long.to_string()),
            help: help.to_string(),
            value: false,
            optional_value: false,
            repeatable: false,
            possible: Vec::new(),
            positional: false,
        }
    }

    /// Every spelling of the option, long before short.
    fn spellings(&self) -> Vec<String> {
        let mut v = Vec::new();
        if let Some(l) = &self.long {
            v.push(std::format!("--{}", l));
        }
        if let Some(s) = self.short {
            v.push(std::format!("-{}", s));
        }
        v
    }

    fn placeholder(&self) -> String {
        self.name.to_uppercase()
    }
}

fn opt_of(arg: &Arg) -> Opt {
    Opt {
        name: arg.name.clone(),
        short: arg.short,
        long: arg.long.clone(),
        help: arg.help.clone().unwrap_or_default(),
        value: arg.takes_value,
        optional_value: arg.optional_value.is_some(),
        repeatable: arg.multiple,
        possible: arg.possible_values.clone(),
        positional: arg.positional,
    }
}

/// Every option the shells should offer: the visible declared ones,
/// then the parser's builtins when they are enabled.
fn options(app: &App) -> Vec<Opt> {
    let mut v: Vec<Opt> = app.args.iter().filter(|a| !a.hidden).map(opt_of).collect();

    if !app.settings.disable_help_flag {
        v.push(Opt::builtin('h', "help", "Print help"));
    }
    if !app.settings.disable_version_flag && app.version.is_some() {
        v.push(Opt::builtin('V', "version", "Print version"));
    }
    v
}

pub fn generate_completion(app: &App, shell: Shell) -> String {
    match shell {
        Shell::Bash => generate_bash(app),
        Shell::Zsh => generate_zsh(app),
        Shell::Fish => generate_fish(app),
        Shell::PowerShell => generate_powershell(app),
    }
}

fn generate_bash(app: &App) -> String {
    let name = &app.name;
    let opts = options(app);

    let mut words: Vec<String> = Vec::new();
    for o in &opts {
        for s in o.spellings() {
            words.push(s);
        }
    }

    let mut script = std::format!(
        "# bash completion for {name} — generated by `{name} --completions bash`.\n\
         #\n\
         #   source <({name} --completions bash)\n\
         #\n\
         # Self-contained: no dependency on the bash-completion package.\n\
         _{name}() {{\n\
         \x20   local cur prev\n\
         \x20   COMPREPLY=()\n\
         \x20   cur=\"${{COMP_WORDS[COMP_CWORD]}}\"\n\
         \x20   prev=\"${{COMP_WORDS[COMP_CWORD-1]-}}\"\n\
         \n\
         \x20   case \"$cur\" in\n"
    );

    // `--opt=v`: complete the half after the `=` from the value list.
    for o in opts
        .iter()
        .filter(|o| o.value && !o.possible.is_empty() && !o.positional)
    {
        let words = o.possible.join(" ");
        for spelling in o.spellings() {
            script.push_str(&std::format!(
                "        {spelling}=*)\n\
                 \x20           COMPREPLY=( $(compgen -W \"{words}\" -- \"${{cur#*=}}\") )\n\
                 \x20           compopt -o nospace 2>/dev/null\n\
                 \x20           return 0\n\
                 \x20           ;;\n"
            ));
        }
    }

    script.push_str("        *)\n            ;;\n    esac\n\n    case \"$prev\" in\n");

    // `--opt <TAB>`: offer the value list and stop — falling through to
    // the flag list would overwrite the completion the user asked for.
    for o in opts.iter().filter(|o| o.value && !o.positional) {
        let body = if o.possible.is_empty() {
            // A value nothing can be suggested for: stop rather than
            // offer unrelated words.
            String::new()
        } else {
            std::format!(
                "            COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") )\n",
                o.possible.join(" ")
            )
        };
        script.push_str(&std::format!(
            "        {})\n{}            return 0\n            ;;\n",
            o.spellings().join("|"),
            body
        ));
    }

    script.push_str("        --)\n            return 0\n            ;;\n    esac\n\n");

    script.push_str(&std::format!(
        "    COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") )\n\
         }}\n\
         \n\
         complete -o bashdefault -F _{name} {name}\n",
        words.join(" ")
    ));

    script
}

fn generate_zsh(app: &App) -> String {
    let name = &app.name;
    let opts = options(app);

    let mut script = std::format!(
        "#compdef {name}\n\
         # zsh completion for {name} — generated by `{name} --completions zsh`.\n\
         #\n\
         #   {name} --completions zsh > \"${{fpath[1]}}/_{name}\"\n\
         #\n\
         _{name}() {{\n\
         \x20   local -a opts\n\
         \x20   opts=(\n"
    );

    for o in opts.iter().filter(|o| !o.positional) {
        // A short and its long are two spellings of one option, so each
        // rules the other out; anything else is left alone rather than
        // guessed at.
        let excl = match (o.short, &o.long) {
            (Some(s), Some(l)) => std::format!("(-{} --{})", s, l),
            _ => String::new(),
        };
        let repeat = if o.repeatable { "*" } else { "" };
        let help = zsh_escape(&o.help);
        let tail = zsh_value_tail(o);

        if let Some(s) = o.short {
            let mut spec = std::format!("{excl}{repeat}-{s}[{help}]");
            if o.value {
                spec.push_str(&tail);
            }
            script.push_str(&std::format!("        '{}'\n", spec));
        }
        if let Some(l) = &o.long {
            // `--opt=-` is how zsh spells "the value may be left off";
            // `--opt=` is the required-value form.
            let joiner = if !o.value {
                ""
            } else if o.optional_value {
                "=-"
            } else {
                "="
            };
            let tail_if = if o.value { tail.as_str() } else { "" };
            let spec = std::format!("{excl}{repeat}--{l}{joiner}[{help}]{tail_if}");
            script.push_str(&std::format!("        '{}'\n", spec));
        }
    }

    for o in opts.iter().filter(|o| o.positional) {
        let slot = if o.repeatable { "*" } else { "1" };
        let action = if o.repeatable { "_files" } else { "" };
        script.push_str(&std::format!(
            "        '{slot}:{0}:{action}'\n",
            o.placeholder()
        ));
    }

    script.push_str(&std::format!(
        "    )\n\
         \n\
         \x20   _arguments -s -S $opts\n\
         }}\n\
         \n\
         _{name} \"$@\"\n"
    ));

    script
}

/// The `:message:action` tail zsh appends to a spec that takes a value.
/// A single `:` makes the value required, `::` makes it optional.
fn zsh_value_tail(opt: &Opt) -> String {
    let action = if opt.possible.is_empty() {
        String::new()
    } else {
        std::format!("({})", opt.possible.join(" "))
    };
    let colon = if opt.optional_value { "::" } else { ":" };
    std::format!("{colon}{0}:{1}", opt.placeholder(), action)
}

/// zsh reads `[`, `]` and `:` inside an `_arguments` spec as syntax.
fn zsh_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '[' | ']' | ':' => {
                out.push('\\');
                out.push(c);
            }
            '\'' => out.push_str("''"),
            _ => out.push(c),
        }
    }
    out
}

fn generate_fish(app: &App) -> String {
    let name = &app.name;
    let mut script = std::format!(
        "# fish completion for {name} — generated by `{name} --completions fish`.\n\
         #\n\
         #   {name} --completions fish > ~/.config/fish/completions/{name}.fish\n"
    );

    for o in options(app).iter().filter(|o| !o.positional) {
        let mut line = std::format!("complete -c {name}");
        if let Some(s) = o.short {
            line.push_str(&std::format!(" -s {s}"));
        }
        if let Some(l) = &o.long {
            line.push_str(&std::format!(" -l {l}"));
        }
        if o.value {
            // -x (exclusive) when the values are known: nothing else may
            // follow, and no file names are offered. -r (requires a
            // value) when they are not.
            if o.possible.is_empty() {
                line.push_str(" -r");
            } else {
                line.push_str(&std::format!(" -x -a '{}'", o.possible.join(" ")));
            }
        }
        if !o.help.is_empty() {
            line.push_str(&std::format!(" -d '{}'", fish_quote(&o.help)));
        }
        script.push_str(&line);
        script.push('\n');
    }

    script
}

/// fish has no escape character inside a single-quoted string: a
/// backslash there is a backslash, so `don\'t` would reach the
/// description with the backslash still in it and the rest of the word
/// outside the quotes. Close, escape, reopen instead.
fn fish_quote(s: &str) -> String {
    s.replace('\'', "'\\''")
}

fn generate_powershell(app: &App) -> String {
    let name = &app.name;
    let mut script = std::format!(
        "# PowerShell completion for {name} — generated by `{name} --completions powershell`.\n\
         #\n\
         #   {name} --completions powershell | Out-String | Invoke-Expression\n\
         Register-ArgumentCompleter -Native -CommandName {name} -ScriptBlock {{\n\
         \x20   param($commandName, $wordToComplete, $commandAst, $cursorPosition)\n\
         \n\
         \x20   $completions = @(\n"
    );

    for o in options(app).iter().filter(|o| !o.positional) {
        let kind = if o.value { "ParameterName" } else { "Option" };
        let help = o.help.replace('\'', "''");
        for spelling in o.spellings() {
            script.push_str(&std::format!(
                "        [CompletionResult]::new('{spelling}', '{spelling}', \
                 [CompletionResultType]::{kind}, '{help}')\n"
            ));
        }
    }

    script.push_str(
        "    )\n\
         \n\
         \x20   $completions.Where{ $_.CompletionText -like \"$wordToComplete*\" } |\n\
         \x20       Sort-Object CompletionText\n\
         }\n",
    );

    script
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The flags a shell is expected to offer, read from the argument
    /// table itself and nowhere else. Going through [`options`] would be
    /// circular: that is the function under test.
    fn declared_flags(app: &App) -> Vec<(&str, Option<char>, Option<&str>)> {
        app.args
            .iter()
            .filter(|a| !a.hidden && !a.positional)
            .map(|a| (a.name.as_str(), a.short, a.long.as_deref()))
            .collect()
    }

    /// The whole point of generating from the table: a flag that exists
    /// but does not appear in a script is a completion that silently
    /// stopped working. This walks the real argument table of the real
    /// binary, so it goes red the moment a flag is added and the
    /// generator stops covering it.
    #[test]
    fn every_declared_flag_reaches_every_shell() {
        let app = crate::app();
        let flags = declared_flags(&app);
        assert!(
            flags.len() > 30,
            "only {} flags parsed; this test would pass vacuously",
            flags.len()
        );

        for shell in Shell::ALL {
            let script = generate_completion(&app, shell);
            for (_, short, long) in &flags {
                // fish spells a flag `-l long` / `-s x` and has no `--`.
                let spellings: Vec<String> = match shell {
                    Shell::Fish => [
                        long.map(|l| std::format!("-l {l}")),
                        short.map(|s| std::format!("-s {s}")),
                    ],
                    _ => [
                        long.map(|l| std::format!("--{l}")),
                        short.map(|s| std::format!("-{s}")),
                    ],
                }
                .into_iter()
                .flatten()
                .collect();
                for spelling in spellings {
                    assert!(
                        script.contains(&spelling),
                        "{:?} completion is missing {spelling}",
                        shell
                    );
                }
            }
        }
    }

    /// The count is checked as well as the contents: a generator that
    /// silently stopped emitting short forms, say, would keep the long
    /// names passing.
    #[test]
    fn every_declared_short_flag_reaches_every_shell() {
        let app = crate::app();
        let shorts: Vec<char> = declared_flags(&app)
            .iter()
            .filter_map(|(_, s, _)| *s)
            .collect();
        assert!(shorts.len() > 15, "only {} shorts", shorts.len());
        for shell in Shell::ALL {
            let script = generate_completion(&app, shell);
            for s in &shorts {
                let spelling = if shell == Shell::Fish {
                    std::format!("-s {s}")
                } else {
                    std::format!("-{s}")
                };
                assert!(
                    script.contains(&spelling),
                    "{shell:?} is missing {spelling}"
                );
            }
        }
    }

    /// The list `--completions` accepts is the list of shells this build
    /// can generate, not a second copy of it that can fall behind.
    #[test]
    fn the_shell_argument_accepts_exactly_the_generators() {
        let arg = crate::app()
            .get_arg("completions")
            .expect("--completions is declared")
            .clone();
        let accepted: Vec<&str> = arg.possible_values.iter().map(String::as_str).collect();
        let built: Vec<&str> = Shell::ALL.iter().map(|s| s.name()).collect();
        assert_eq!(accepted, built);
        for shell in Shell::ALL {
            assert!(Shell::from_name(shell.name()).is_some());
        }
    }

    #[test]
    fn shell_from_name() {
        assert_eq!(Shell::from_name("bash"), Some(Shell::Bash));
        assert_eq!(Shell::from_name("sh"), Some(Shell::Bash));
        assert_eq!(Shell::from_name("ZSH"), Some(Shell::Zsh));
        assert_eq!(Shell::from_name("fish"), Some(Shell::Fish));
        assert_eq!(Shell::from_name("pwsh"), Some(Shell::PowerShell));
        assert_eq!(Shell::from_name("tcsh"), None);
    }

    #[test]
    fn hidden_flags_are_not_offered() {
        let app = App::new("t").arg(Arg::new("secret").long("secret").hidden(true));
        assert!(!generate_completion(&app, Shell::Bash).contains("--secret"));
        assert!(!generate_completion(&app, Shell::Zsh).contains("--secret"));
        assert!(!generate_completion(&app, Shell::Fish).contains("--secret"));
        assert!(!generate_completion(&app, Shell::PowerShell).contains("--secret"));
    }

    #[test]
    fn the_parser_builtins_are_offered_because_they_work() {
        let app = App::new("t").version("1.0").arg(Arg::new("v").short('v'));
        for shell in Shell::ALL {
            let script = generate_completion(&app, shell);
            assert!(script.contains("help"), "{shell:?}: {script}");
            assert!(script.contains("version"), "{shell:?}: {script}");
        }
    }

    #[test]
    fn a_disabled_builtin_is_not_offered() {
        let app = App::new("t")
            .version("1.0")
            .disable_help_flag(true)
            .disable_version_flag(true);
        let script = generate_completion(&app, Shell::Bash);
        assert!(!script.contains("--help"), "{script}");
        assert!(!script.contains("--version"), "{script}");
    }

    #[test]
    fn zsh_entries_are_one_per_line() {
        // Entries running together glue `-i[...]-S[...]` into one word
        // zsh then cannot parse. Every entry must own its line.
        let script = generate_completion(&crate::app(), Shell::Zsh);
        let body = script
            .split("opts=(\n")
            .nth(1)
            .and_then(|s| s.split("\n    )\n").next())
            .expect("the opts array");
        for line in body.lines().filter(|l| !l.trim().is_empty()) {
            assert!(
                line.starts_with("        '") && line.ends_with('\''),
                "malformed zsh entry: {line:?}"
            );
        }
        assert!(!body.contains("]-"), "entries ran together: {body}");
    }

    /// Every arm of `case "$prev"` has to end the function. An arm that
    /// falls through reaches the flag-list line at the bottom, which
    /// overwrites what it just computed — the completion looks like it ran
    /// and offered the wrong thing.
    #[test]
    fn every_bash_case_arm_returns() {
        let script = generate_completion(&crate::app(), Shell::Bash);
        let body = script
            .split("case \"$prev\" in\n")
            .nth(1)
            .and_then(|s| s.split("    esac\n").next())
            .expect("the $prev case");
        for arm in body.split("\n        --)").next().unwrap().split(";;") {
            let arm = arm.trim();
            if arm.is_empty() {
                continue;
            }
            assert!(arm.contains("return 0"), "arm falls through: {arm:?}");
        }
    }

    /// Reads a fish single-quoted word the way fish's lexer does: a quote
    /// opens and closes, a backslash outside quotes escapes, and there is
    /// no escape of any kind inside one.
    fn fish_d_values(script: &str) -> Vec<String> {
        let b: Vec<char> = script.chars().collect();
        let mut out = Vec::new();
        let mut i = 0;
        while i < b.len() {
            let is_d = i + 3 < b.len()
                && b[i] == '-'
                && b[i + 1] == 'd'
                && b[i + 2] == ' '
                && b[i + 3] == '\'';
            if !is_d {
                i += 1;
                continue;
            }
            i += 4;
            let mut value = String::new();
            let mut quoted = true;
            while i < b.len() {
                if !quoted && (b[i] == ' ' || b[i] == '\n') {
                    break;
                }
                if !quoted && b[i] == '\\' && b.get(i + 1) == Some(&'\'') {
                    value.push('\'');
                    i += 2;
                    continue;
                }
                if b[i] == '\'' {
                    quoted = !quoted;
                    i += 1;
                    continue;
                }
                value.push(b[i]);
                i += 1;
            }
            out.push(value);
        }
        out
    }

    /// Every description fish ends up with has to be the help text the
    /// table holds, character for character. rgx's own help is full of
    /// apostrophes ("don't respect ignore files"), and getting the
    /// quoting wrong silently truncates them.
    #[test]
    fn fish_receives_the_help_text_verbatim() {
        let app = crate::app();
        let mut expected: Vec<String> = app
            .args
            .iter()
            .filter(|a| !a.hidden && !a.positional)
            .filter_map(|a| a.help.clone())
            .filter(|h| !h.is_empty())
            .collect();
        expected.push("Print help".to_string());
        expected.push("Print version".to_string());
        let mut got = fish_d_values(&generate_completion(&app, Shell::Fish));
        expected.sort();
        expected.dedup();
        got.sort();
        got.dedup();
        assert_eq!(got, expected);
    }

    #[test]
    fn zsh_escapes_the_characters_it_reads_as_syntax() {
        assert_eq!(zsh_escape("a [b] c: d"), "a \\[b\\] c\\: d");
        // A quote inside a single-quoted zsh string is written by closing
        // and reopening; the two halves concatenate back to one word.
        assert_eq!(zsh_escape("don't"), "don''t");
        let script = generate_completion(&crate::app(), Shell::Zsh);
        assert!(script.contains("don''t"), "the text survives: {script}");
        assert!(!script.contains("don't"), "an unescaped quote: {script}");
    }

    #[test]
    fn zsh_positional_guessing_is_derived_not_listed() {
        let script = generate_completion(&crate::app(), Shell::Zsh);
        assert!(script.contains("'1:PATTERN:'"), "{}", script);
        assert!(script.contains("'*:PATHS:_files'"), "{}", script);
    }
}

//! What a file's *name* says about it.
//!
//! Two facts, both derived from the extension and from nothing else: the
//! MIME type and, for the source files, the language. They live here and
//! not in an adapter because the pipeline knows them for every file,
//! claimed or not — a `.pdf` nobody could decode still says it is a PDF.
//!
//! **What this is not.** The IANA registry, and not a detector. A table of
//! the types this project meets and the languages a source file is written
//! in. An extension is a claim, not a proof: a `.pdf` that is not a PDF
//! still says `application/pdf` here, and the adapter that answers for the
//! file is the one that knows what it is. The two facts therefore disagree
//! on a misnamed file, and that disagreement is worth having — it is what
//! separates "the name says" from "the bytes say".
//!
//! The tables are `match` arms rather than a sorted table and a binary
//! search: the compiler turns them into a decision tree, and a table that
//! has to be kept sorted is a table that gets out of date.


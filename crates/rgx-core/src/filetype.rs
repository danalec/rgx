#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_known_extension_has_a_mime_type() {
        assert_eq!(mime_of("pdf"), Some("application/pdf"));
        assert_eq!(mime_of("zip"), Some("application/zip"));
        assert_eq!(mime_of("safetensors"), Some("model/safetensors"));
        assert_eq!(mime_of("eml"), Some("message/rfc822"));
    }

    #[test]
    fn an_unknown_extension_has_none() {
        assert_eq!(mime_of("qqq"), None);
        assert_eq!(lang_of("qqq"), None);
    }

    #[test]
    fn a_source_extension_has_a_language() {
        assert_eq!(lang_of("rs"), Some("rust"));
        assert_eq!(lang_of("py"), Some("python"));
        assert_eq!(lang_of("ts"), Some("typescript"));
    }

    /// A language is never a MIME type and a MIME type is never a
    /// language: the two tables answer different questions, and an
    /// extension that is in both (`csv`) says both.
    #[test]
    fn the_two_tables_are_independent() {
        assert_eq!(mime_of("csv"), Some("text/csv"));
        assert_eq!(lang_of("csv"), Some("csv"));
        assert_eq!(mime_of("rs"), Some("text/x-rust"));
        assert_eq!(lang_of("rs"), Some("rust"));
    }
}

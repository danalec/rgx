/// A legacy multi-byte CJK encoding.
///
/// The high half of these encodings is a *pair* of bytes, not one, so the
/// single-byte table above cannot hold it: the table is indexed by the
/// lead byte and then by the trail byte, which is a two-level lookup with
/// no search in it.
///
/// The tables are generated from the reference implementation by
/// `scripts/gen_charset_mb_tables.py`, the same way the single-byte ones
/// are.
pub struct MultiByte {
    /// The encoding's name, for the facts and for the error message.
    pub name: &'static str,
    /// The characters that stand alone in 0x80..=0xFF, and zero where
    /// there is none: Shift_JIS and EUC-JP's half-width katakana.
    pub single: &'static [u32; 128],
    /// The lowest and the highest lead byte of the two-byte form.
    pub lead_min: u8,
    pub lead_max: u8,
    /// The lowest and the highest trail byte of the two-byte form.
    pub trail_min: u8,
    pub trail_max: u8,
    /// The lead bytes that start a two-byte character, as ranges.
    pub leads: &'static [(u8, u8)],
    /// The trail bytes a two-byte character may use, as ranges.
    pub trails: &'static [(u8, u8)],
    /// The two-byte table, indexed by lead and then by trail. A position
    /// the encoding does not use is zero.
    pub table: &'static [u32],
    /// The three-byte form, when the encoding has one.
    pub prefix3: Option<Prefix3>,
    /// The four-byte form's ranges, when the encoding has one: the first
    /// pointer of the run, its length, and the codepoint of its first
    /// position.
    pub quad: &'static [(u32, u32, u32)],
}

/// The three-byte form of a multi-byte encoding: a prefix byte and two
/// trail bytes. EUC-JP's JIS X 0212 is the one that has it.
pub struct Prefix3 {
    /// The byte that starts the form.
    pub prefix: u8,
    /// The lowest and the highest byte of the two that follow.
    pub trail_min: u8,
    pub trail_max: u8,
    /// The table, indexed by the first byte and then by the second.
    pub table: &'static [u32],
}

/// Two encodings are the same encoding when they are the same table: the
/// tables are static, so the address says it.
impl PartialEq for MultiByte {
    fn eq(&self, other: &Self) -> bool {
        core::ptr::eq(self, other)
    }
}

impl Eq for MultiByte {}

impl core::fmt::Debug for MultiByte {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(self.name)
    }
}

/// A charset this module can decode.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Charset {
    /// UTF-8. The bytes are already what they claim to be.
    Utf8,
    /// US-ASCII. Decoded as Windows-1252, which is what the WHATWG
    /// encoding standard does with the label: a browser reading
    /// `charset=us-ascii` does not throw the high half away.
    Ascii,
    /// ISO-8859-1 (Latin-1): every byte is the codepoint of the same value.
    Latin1,
    /// A legacy single-byte encoding. The table covers 0x80..=0xFF; the low
    /// half is ASCII in all of them.
    SingleByte(&'static [u16; 128]),
    /// A legacy single-byte encoding whose low half is not ASCII: EBCDIC.
    ///
    /// The table covers every byte, 0x00..=0xFF, because the code page
    /// puts its space at 0x40 and its punctuation where ASCII has its
    /// letters: a table of the high half alone would read them wrongly.
    SingleByteFull(&'static [u16; 256]),
    /// A legacy multi-byte CJK encoding. The high half of these is a
    /// *pair* of bytes, so the table is indexed by the lead byte and then
    /// by the trail byte.
    MultiByte(&'static MultiByte),
    /// UTF-16, with a byte-order mark if there is one and big-endian
    /// without (RFC 2781 §4.3).
    Utf16,
    /// UTF-16 little-endian, with a byte-order mark if there is one.
    Utf16Le,
    /// UTF-16 big-endian, with a byte-order mark if there is one.
    Utf16Be,
    /// ISO-2022-JP: the encoding that declares its own character set as it
    /// goes. An escape sequence switches the set, and the bytes after it
    /// are read in the set it names.
    Iso2022Jp,
    /// UTF-7: the `+<base64>-` encoding of RFC 2152, where a character
    /// that is not ASCII is written as base64 between a `+` and a `-`.
    Utf7,
}


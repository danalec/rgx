//! Decoding a byte stream in a charset the data itself names.
//!
//! **Why this exists.** A file, a message or a document often says what
//! encoding its bytes are in: a MIME part carries `charset=`, an HTML page
//! carries `<meta charset>`, an RFC 2047 header carries `=?UTF-8?B?...?=`,
//! and the BIFF5 record format of an old spreadsheet says cp1252 in the
//! format itself. A reader that ignores the declaration and decodes the
//! bytes as UTF-8 does not read them *differently* -- it **destroys** them:
//! every byte above 0x7F becomes U+FFFD, the character is gone, and a search
//! for it cannot find it. The byte is still on the disk, but the answer the
//! tool gives no longer contains it.
//!
//! That is why this is a decoder and not a guesser. The declaration is
//! honoured when it names an encoding this module knows, and when it does
//! not, the fallback is the one that cannot lose a byte.
//!
//! **The fallback.** [`decode_lenient`] keeps valid UTF-8 as it is and
//! decodes anything else as Latin-1, which maps every byte to the codepoint
//! of the same value. It is a bijection on bytes, so no byte is ever
//! replaced by U+FFFD, and a file whose charset nobody declared stays
//! searchable in its ASCII part (which every one of these encodings
//! contains unchanged) and in its high bytes (which a Latin-1 reading
//! preserves exactly, even where the reading is not the right one).
//!
//! **What is here.** The single-byte encodings that dominate real mail and
//! real HTML, and the multi-byte CJK ones -- Shift_JIS, EUC-JP, Big5,
//! EUC-KR and GB18030 -- whose tables are thousands of entries each and
//! are generated from the reference implementation by
//! `scripts/gen_charset_mb_tables.py` and `scripts/gen_charset_tables.py`.
//! A file in one of them is read in the characters it was written in, and
//! a search for one of them finds it.
//!
//! Two of them are *stateful*: ISO-2022-JP and UTF-7 declare what they
//! mean as the stream goes, so the bytes after an escape sequence are read
//! differently from the bytes before it. What they have is a structure --
//! the JIS tables, the base64 alphabet -- and the decoder is a small state
//! machine over it, generated by `scripts/gen_charset_state_tables.py`.


/// Normalise a charset name: lower case, and only letters and digits left.
fn normalize(name: &str) -> alloc::string::String {
    let mut out = alloc::string::String::with_capacity(name.len());
    for b in name.bytes() {
        if b.is_ascii_alphanumeric() {
            out.push(b.to_ascii_lowercase() as char);
        }
    }
    out
}

/// Windows-1252, the legacy single-byte encoding that the BIFF5 record
/// format of an old spreadsheet uses for its strings.
pub const WINDOWS_1252: Charset = Charset::SingleByte(&charset_table::WINDOWS_1252);

/// ISO-8859-1 (Latin-1), where every byte is the codepoint of the same
/// value.
pub const LATIN1: Charset = Charset::Latin1;

/// Shift_JIS, the encoding Japanese Windows used.
pub const SHIFT_JIS: Charset = Charset::MultiByte(&charset_mb_table::SHIFT_JIS);

/// EUC-JP, with the three-byte JIS X 0212.
pub const EUC_JP: Charset = Charset::MultiByte(&charset_mb_table::EUC_JP);

/// Big5, with the Hong Kong extensions.
pub const BIG5: Charset = Charset::MultiByte(&charset_mb_table::BIG5);

/// EUC-KR, with the Unified Hangul.
pub const EUC_KR: Charset = Charset::MultiByte(&charset_mb_table::EUC_KR);

/// GB18030, with its four-byte form.
pub const GB18030: Charset = Charset::MultiByte(&charset_mb_table::GB18030);

/// The character one byte stands for in Windows-1252.
///
/// For the callers that want a character rather than UTF-8 bytes. The
/// table is the shared one above, generated from the reference
/// implementation: a hand-written copy of 32 characters is a transcription
/// error waiting to happen.
pub fn windows_1252_char(b: u8) -> char {
    if b < 0x80 {
        return b as char;
    }
    let cp = charset_table::WINDOWS_1252[(b - 0x80) as usize] as u32;
    char::from_u32(cp).unwrap_or('\u{FFFD}')
}

/// The charset `name` names, or `None` when it names one this module does
/// not know.///
/// The name may be quoted, and may carry anything the caller took it from:
/// a MIME parameter, an HTML attribute, a header. Quotes and separators are
/// dropped rather than matched, because the spellings in the wild differ
/// more than the encodings do.
pub fn lookup(name: &str) -> Option<Charset> {
    let key = normalize(name);
    if key.is_empty() {
        return None;
    }
    ALIASES
        .iter()
        .find(|(alias, _)| *alias == key)
        .map(|(_, cs)| *cs)
}

/// Decode `bytes` in `charset` into UTF-8.
///
/// UTF-8 in, UTF-8 out: the caller gets the same bytes it passed in, so the
/// common case costs a copy and nothing else.
pub fn decode(charset: Charset, bytes: &[u8]) -> Vec<u8> {
    match charset {
        Charset::Utf8 => bytes.to_vec(),
        Charset::Ascii => decode_single(&charset_table::WINDOWS_1252, bytes),
        Charset::Latin1 => decode_single(&LATIN1_TABLE, bytes),
        Charset::SingleByte(table) => decode_single(table, bytes),
        Charset::SingleByteFull(table) => decode_full(table, bytes),
        Charset::MultiByte(mb) => decode_multi(mb, bytes),
        Charset::Utf16 => decode_utf16(utf16_order(bytes), bytes),
        Charset::Utf16Le => decode_utf16(false, bytes),
        Charset::Utf16Be => decode_utf16(true, bytes),
        Charset::Iso2022Jp => decode_iso2022_jp(bytes),
        Charset::Utf7 => decode_utf7(bytes),
    }
}

/// Decode `bytes` in the charset `name` names, or `None` when the name
/// names a charset this module does not know.
///
/// `None` is not an error the caller has to invent an answer for: it means
/// the declaration was not understood, and the caller decides what an
/// unknown declaration is worth. [`decode_lenient`] is the usual answer.
pub fn decode_named(name: &str, bytes: &[u8]) -> Option<Vec<u8>> {
    let cs = lookup(name)?;
    Some(decode(cs, bytes))
}

/// Decode `bytes` without destroying any of them.
///
/// Valid UTF-8 is kept as it is; anything else is read as Latin-1, which
/// maps every byte to the codepoint of the same value and therefore loses
/// nothing. The result is UTF-8 either way.
///
/// This is the answer for a byte stream whose encoding nobody declared, and
/// the answer for a declaration this module cannot honour. Both cases end
/// with the same property: every byte of the input is in the output, and a
/// search for an ASCII string still finds it.
pub fn decode_lenient(bytes: &[u8]) -> Vec<u8> {
    if core::str::from_utf8(bytes).is_ok() {
        return bytes.to_vec();
    }
    decode_single(&LATIN1_TABLE, bytes)
}

/// Latin-1: byte `b` is U+00 + `b`. Written out rather than tabulated
/// because it is the identity on the high half and the table would be 128
/// lines of `0x00XX`.
static LATIN1_TABLE: [u16; 128] = {
    let mut t = [0u16; 128];
    let mut i = 0;
    while i < 128 {
        t[i] = 0x80 + i as u16;
        i += 1;
    }
    t
};

/// Decode a single-byte stream: ASCII below 0x80, the table above it.
fn decode_single(table: &[u16; 128], bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + bytes.len() / 4);
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b < 0x80 {
            out.push(b);
            i += 1;
            continue;
        }
        let cp = table[(b - 0x80) as usize];
        push_utf8(cp as u32, &mut out);
        i += 1;
    }
    out
}

/// Decode a single-byte stream whose low half is not ASCII: every byte is
/// looked up in the table.
///
/// EBCDIC is the one that needs this. Its space is 0x40 and its full
/// stop is 0x4B, where ASCII has an `@` and a `K`: a table of the high
/// half alone, with the low half read as ASCII, turns the punctuation of
/// the file into letters.
fn decode_full(table: &[u16; 256], bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + bytes.len() / 4);
    for &b in bytes {
        push_utf8(table[b as usize] as u32, &mut out);
    }
    out
}

/// Decode a multi-byte stream: ASCII below 0x80, the encoding's own forms
/// above it.
///
/// The forms are tried longest first, and the one that fits is the one the
/// encoding itself would take: GB18030's four-byte form starts with a lead
/// byte the two-byte form also uses, and the four-byte form's second byte
/// is never a valid trail, so the two cannot be confused. A byte that fits
/// nothing is U+FFFD, and the stream continues at the next byte -- the
/// WHATWG encoding standard's own rule, which is also the one that never
/// loses the byte after it.
fn decode_multi(mb: &MultiByte, bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + bytes.len() / 4);
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b < 0x80 {
            out.push(b);
            i += 1;
            continue;
        }
        // The four-byte form: GB18030's extension to the Unicode planes.
        if !mb.quad.is_empty() && i + 3 < bytes.len() {
            if let Some(cp) = quad_lookup(mb, &bytes[i..i + 4]) {
                push_utf8(cp, &mut out);
                i += 4;
                continue;
            }
        }
        // The three-byte form: EUC-JP's JIS X 0212.
        if let Some(p3) = mb.prefix3.as_ref() {
            if b == p3.prefix && i + 2 < bytes.len() {
                let t1 = bytes[i + 1];
                let t2 = bytes[i + 2];
                if t1 >= p3.trail_min
                    && t1 <= p3.trail_max
                    && t2 >= p3.trail_min
                    && t2 <= p3.trail_max
                {
                    let stride = (p3.trail_max - p3.trail_min + 1) as usize;
                    let cp = p3.table
                        [(t1 - p3.trail_min) as usize * stride + (t2 - p3.trail_min) as usize];
                    if cp != 0 {
                        push_utf8(cp, &mut out);
                        i += 3;
                        continue;
                    }
                }
            }
        }
        // The two-byte form.
        if in_ranges(mb.leads, b) && i + 1 < bytes.len() {
            let t = bytes[i + 1];
            if in_ranges(mb.trails, t) && t >= mb.trail_min && t <= mb.trail_max {
                let stride = (mb.trail_max - mb.trail_min + 1) as usize;
                let cp =
                    mb.table[(b - mb.lead_min) as usize * stride + (t - mb.trail_min) as usize];
                if cp != 0 {
                    push_utf8(cp, &mut out);
                    i += 2;
                    continue;
                }
            }
        }
        // A single high byte: the half-width katakana, or nothing.
        let cp = mb.single[(b - 0x80) as usize];
        push_utf8(if cp == 0 { 0xFFFD } else { cp }, &mut out);
        i += 1;
    }
    out
}

/// true when `byte` is in one of the inclusive ranges.
fn in_ranges(ranges: &[(u8, u8)], byte: u8) -> bool {
    ranges.iter().any(|(lo, hi)| byte >= *lo && byte <= *hi)
}

/// The codepoint of GB18030's four-byte form, when the four bytes are one.
///
/// The four bytes do not map to Unicode one by one: they map through a
/// *pointer space*, and the standard's table says which runs of that space
/// are consecutive in Unicode. The runs are sorted by their first pointer,
/// so a binary search finds the one that holds this pointer.
fn quad_lookup(mb: &MultiByte, q: &[u8]) -> Option<u32> {
    if !(0x81..=0xFE).contains(&q[0])
        || !(0x30..=0x39).contains(&q[1])
        || !(0x81..=0xFE).contains(&q[2])
        || !(0x30..=0x39).contains(&q[3])
    {
        return None;
    }
    let pointer = (q[0] as u32 - 0x81) * 12600
        + (q[1] as u32 - 0x30) * 1260
        + (q[2] as u32 - 0x81) * 10
        + (q[3] as u32 - 0x30);
    let mut lo = 0usize;
    let mut hi = mb.quad.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (start, len, base) = mb.quad[mid];
        if pointer < start {
            hi = mid;
        } else if pointer >= start + len {
            lo = mid + 1;
        } else {
            return Some(base + (pointer - start));
        }
    }
    None
}

/// The byte order a UTF-16 stream is in: the mark if there is one, and
/// big-endian without (RFC 2781 §4.3).
fn utf16_order(bytes: &[u8]) -> bool {
    match bytes {
        [0xFF, 0xFE, ..] => false,
        [0xFE, 0xFF, ..] => true,
        _ => true,
    }
}

/// Decode UTF-16 into UTF-8, skipping a leading mark.
///
/// A mark is a mark: it is not a character, and leaving it in would put a
/// U+FEFF at the head of every line the file has.
fn decode_utf16(be: bool, bytes: &[u8]) -> Vec<u8> {
    let body = match bytes {
        [0xFF, 0xFE, rest @ ..] if !be => rest,
        [0xFE, 0xFF, rest @ ..] if be => rest,
        _ => bytes,
    };
    crate::encoding::decode_utf16(be, body)
}

/// The character set an ISO-2022-JP stream is in.
///
/// ISO-2022-JP declares the set it is in as it goes: an escape sequence
/// switches it, and the bytes after it are read in the set it names. This
/// is the state that switch moves.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Iso2022Jp {
    /// `ESC ( B`: ASCII, where the backslash is a backslash.
    Ascii,
    /// `ESC ( J`: JIS X 0201 Roman, where the backslash is the yen sign
    /// and the tilde is the overline (RFC 1468 §2).
    Roman,
    /// `ESC ( I`, and the `SO` shift: JIS X 0201 katakana, one byte each.
    Katakana,
    /// `ESC $ @` and `ESC $ B`: JIS X 0208, two bytes each.
    JisX0208,
    /// `ESC $ ( D`: JIS X 0212, two bytes each.
    JisX0212,
}

/// The designation an ISO-2022-JP escape sequence names, and how long the
/// sequence is.
///
/// RFC 1468 §2 gives the four sequences ISO-2022-JP itself uses: `ESC ( B`,
/// `ESC ( J`, `ESC $ @` and `ESC $ B`. The katakana set (`ESC ( I`) and
/// JIS X 0212 (`ESC $ ( D`) are the two the WHATWG encoding standard adds
/// on top of it, and Python's `iso2022_jp_2` reads the second of them.
/// The longest match wins, so `ESC $ ( D` is not read as `ESC $` followed
/// by `( D`.
fn iso2022_designation(bytes: &[u8], at: usize) -> Option<(Iso2022Jp, usize)> {
    let rest = &bytes[at..];
    if rest.starts_with(b"\x1b$(D") {
        Some((Iso2022Jp::JisX0212, 4))
    } else if rest.starts_with(b"\x1b(B") {
        Some((Iso2022Jp::Ascii, 3))
    } else if rest.starts_with(b"\x1b(J") {
        Some((Iso2022Jp::Roman, 3))
    } else if rest.starts_with(b"\x1b(I") {
        Some((Iso2022Jp::Katakana, 3))
    } else if rest.starts_with(b"\x1b$@") || rest.starts_with(b"\x1b$B") {
        // The two revisions of JIS X 0208, read with the same table.
        Some((Iso2022Jp::JisX0208, 3))
    } else {
        None
    }
}

/// How many bytes a malformed ISO-2022-JP escape sequence occupies.
///
/// The escape and the bytes that were read to decide it was malformed: the
/// designation is read one byte at a time, and the bytes read are the ones
/// that could have been part of one. The bytes after that are read again in
/// the set that is current, so a malformed escape costs the stream one
/// replacement character and nothing else.
fn iso2022_malformed_len(bytes: &[u8], at: usize) -> usize {
    let rest = &bytes[at..];
    match rest.get(1) {
        None => 1,
        Some(b'(') => rest.len().min(3),
        Some(b'$') => match rest.get(2) {
            Some(b'(') => rest.len().min(4),
            _ => rest.len().min(3),
        },
        Some(_) => 2,
    }
}

/// Decode an ISO-2022-JP stream.
///
/// What happens when the stream breaks the rules:
///
/// - An escape sequence that names no designation is one U+FFFD. It
///   occupies the escape and the bytes that were read to decide it was
///   malformed, and the bytes after that are read again.
/// - A byte that is not a character in the set that is current is one
///   U+FFFD, and the stream goes on at the next byte.
/// - A two-byte character whose second byte is not a trail byte is one
///   U+FFFD for the lead byte, and the byte after it is read again.
/// - A pair the table does not map is one U+FFFD, and both bytes are
///   consumed: the pair is one character position.
///
/// The `SO` shift is the one rule that is not Python's: `SO` (0x0E) shifts
/// to the katakana set and `SI` (0x0F) shifts back to the set that was
/// current before the `SO`, which in the legacy streams that use them is
/// the Roman set. RFC 1468 §3 forbids both as characters in an ISO-2022-JP
/// stream, so a conforming stream never reaches that branch; Python's
/// `iso2022_jp` passes them through as the control characters they are,
/// which reads those streams wrongly.
fn decode_iso2022_jp(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + bytes.len() / 4);
    let mut state = Iso2022Jp::Ascii;
    // The set an `SI` shifts back to: the set that was current before the
    // last `SO`, which is ASCII until there is one (RFC 1468: the text
    // starts in ASCII).
    let mut g0 = Iso2022Jp::Ascii;
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b == 0x1B {
            match iso2022_designation(bytes, i) {
                Some((next, len)) => {
                    state = next;
                    i += len;
                }
                None => {
                    push_utf8(0xFFFD, &mut out);
                    i += iso2022_malformed_len(bytes, i);
                }
            }
            continue;
        }
        match state {
            Iso2022Jp::Ascii => {
                if b == 0x0E {
                    g0 = state;
                    state = Iso2022Jp::Katakana;
                } else if b == 0x0F {
                    state = g0;
                } else if b < 0x80 {
                    out.push(b);
                } else {
                    push_utf8(0xFFFD, &mut out);
                }
                i += 1;
            }
            Iso2022Jp::Roman => {
                if b == 0x0E {
                    g0 = state;
                    state = Iso2022Jp::Katakana;
                } else if b == 0x0F {
                    state = g0;
                } else if b < 0x80 {
                    let cp = charset_state_table::JIS_X_0201_ROMAN[b as usize];
                    push_utf8(if cp == 0 { 0xFFFD } else { cp as u32 }, &mut out);
                } else {
                    push_utf8(0xFFFD, &mut out);
                }
                i += 1;
            }
            Iso2022Jp::Katakana => {
                if b == 0x0E {
                    g0 = state;
                    state = Iso2022Jp::Katakana;
                } else if b == 0x0F {
                    state = g0;
                } else if (0x21..=0x5F).contains(&b) {
                    let cp = charset_state_table::JIS_X_0201_KATAKANA[b as usize];
                    push_utf8(if cp == 0 { 0xFFFD } else { cp as u32 }, &mut out);
                } else {
                    push_utf8(0xFFFD, &mut out);
                }
                i += 1;
            }
            Iso2022Jp::JisX0208 | Iso2022Jp::JisX0212 => {
                if !(0x21..=0x7E).contains(&b) {
                    // Not a byte of a two-byte character.
                    push_utf8(0xFFFD, &mut out);
                    i += 1;
                    continue;
                }
                let trail = match bytes.get(i + 1) {
                    Some(&trail) => trail,
                    None => {
                        // The character is cut short by the end of the stream.
                        push_utf8(0xFFFD, &mut out);
                        i += 1;
                        continue;
                    }
                };
                if !(0x21..=0x7E).contains(&trail) {
                    // The byte after the lead byte is not a trail byte: the
                    // lead byte is one replacement, and the byte after it is
                    // read again in the set that is current.
                    push_utf8(0xFFFD, &mut out);
                    i += 1;
                    continue;
                }
                let table = match state {
                    Iso2022Jp::JisX0212 => &charset_state_table::JIS_X_0212,
                    _ => &charset_state_table::JIS_X_0208,
                };
                let cp = table[(b - 0x21) as usize * 94 + (trail - 0x21) as usize];
                if cp == 0 {
                    push_utf8(0xFFFD, &mut out);
                } else {
                    push_utf8(cp as u32, &mut out);
                }
                i += 2;
            }
        }
    }
    out
}

/// The base64 value of a byte in UTF-7's set B, or `None` when the byte is
/// not in the set.
fn utf7_base64_value(b: u8) -> Option<u32> {
    if b >= 0x80 {
        return None;
    }
    let value = charset_state_table::UTF7_BASE64[b as usize];
    if value == 0xFF {
        None
    } else {
        Some(value as u32)
    }
}

/// Decode a UTF-7 stream (RFC 2152).
///
/// UTF-7 writes a character that is not ASCII as base64 between a `+` and
/// a `-`, and writes everything else as itself.
///
/// What happens when the stream breaks the rules:
///
/// - A `+` that is followed by neither a base64 character nor a `-` is one
///   U+FFFD. The byte after the `+` is read again, so a `+` that was not a
///   shift costs the stream one replacement character and nothing else.
///   A `+` at the very end of the stream is that same case with no byte
///   after it: Python's `utf_7` drops it silently, and here it is one
///   replacement, like every other broken section.
/// - A shifted sequence that does not hold a whole 16-bit character, or
///   whose discarded bits are not zero, is one U+FFFD for the whole
///   sequence, and the byte that ended it is read again.
/// - A byte above 0x7F is one U+FFFD: UTF-7 is a 7-bit encoding.
///
/// The `+-` sequence is the plus sign itself, and the `-` that ends a
/// shifted sequence is absorbed by it (RFC 2152 rule 2).
fn decode_utf7(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() + bytes.len() / 4);
    let mut i = 0;
    while i < bytes.len() {
        let b = bytes[i];
        if b != b'+' {
            if b < 0x80 {
                out.push(b);
            } else {
                push_utf8(0xFFFD, &mut out);
            }
            i += 1;
            continue;
        }
        // The shift character.
        i += 1;
        match bytes.get(i) {
            None => {
                // A `+` with nothing after it: an unterminated sequence.
                push_utf8(0xFFFD, &mut out);
                continue;
            }
            Some(&b'-') => {
                // "+-" is the plus sign itself (RFC 2152 rule 2).
                out.push(b'+');
                i += 1;
                continue;
            }
            Some(&c) => {
                if utf7_base64_value(c).is_none() {
                    // A `+` followed by anything that is neither a base64
                    // character nor a `-` is an ill-formed sequence.
                    push_utf8(0xFFFD, &mut out);
                    continue;
                }
            }
        }
        // The shifted sequence: base64 until a character that is not in
        // set B. The `-` that ends it is absorbed; any other byte ends it
        // and is read again.
        let start = i;
        let mut acc: u32 = 0;
        let mut nbits: u32 = 0;
        while i < bytes.len() {
            match utf7_base64_value(bytes[i]) {
                Some(value) => {
                    acc = (acc << 6) | value;
                    nbits += 6;
                    if nbits >= 16 {
                        nbits -= 16;
                        acc &= (1 << nbits) - 1;
                    }
                    i += 1;
                }
                None => break,
            }
        }
        let count = i - start;
        if bytes.get(i) == Some(&b'-') {
            // The `-` that ends a shifted sequence belongs to it (RFC 2152
            // rule 2), and is not a character of the text.
            i += 1;
        }
        let bits = (count * 6) as u32;
        let octets = bits / 8;
        // The sequence must hold a whole number of 16-bit characters, and
        // the bits left over at the end must be zero (RFC 2152 rule 2).
        if octets < 2 || octets % 2 == 1 || acc != 0 {
            push_utf8(0xFFFD, &mut out);
            continue;
        }
        // The characters themselves.
        let mut high: Option<u16> = None;
        let mut acc: u32 = 0;
        let mut nbits: u32 = 0;
        for &c in &bytes[start..start + count] {
            let value = match utf7_base64_value(c) {
                Some(value) => value,
                None => break,
            };
            acc = (acc << 6) | value;
            nbits += 6;
            if nbits < 16 {
                continue;
            }
            nbits -= 16;
            let unit = ((acc >> nbits) & 0xFFFF) as u16;
            acc &= (1 << nbits) - 1;
            // A surrogate pair is one character. A surrogate on its own has
            // no UTF-8 form, and becomes U+FFFD.
            if let Some(h) = high.take() {
                if (0xDC00..=0xDFFF).contains(&unit) {
                    let cp = 0x10000 + (((h as u32) - 0xD800) << 10) + ((unit as u32) - 0xDC00);
                    push_utf8(cp, &mut out);
                    continue;
                }
                push_utf8(0xFFFD, &mut out);
            }
            if (0xD800..=0xDBFF).contains(&unit) {
                high = Some(unit);
            } else if (0xDC00..=0xDFFF).contains(&unit) {
                push_utf8(0xFFFD, &mut out);
            } else {
                push_utf8(unit as u32, &mut out);
            }
        }
        if high.is_some() {
            push_utf8(0xFFFD, &mut out);
        }
    }
    out
}

/// Append the UTF-8 of one codepoint.
fn push_utf8(cp: u32, out: &mut Vec<u8>) {
    if cp < 0x80 {
        out.push(cp as u8);
    } else if cp < 0x800 {
        out.push(0xC0 | (cp >> 6) as u8);
        out.push(0x80 | (cp & 0x3F) as u8);
    } else if cp < 0x10000 {
        out.push(0xE0 | (cp >> 12) as u8);
        out.push(0x80 | ((cp >> 6) & 0x3F) as u8);
        out.push(0x80 | (cp & 0x3F) as u8);
    } else {
        out.push(0xF0 | (cp >> 18) as u8);
        out.push(0x80 | ((cp >> 12) & 0x3F) as u8);
        out.push(0x80 | ((cp >> 6) & 0x3F) as u8);
        out.push(0x80 | (cp & 0x3F) as u8);
    }
}


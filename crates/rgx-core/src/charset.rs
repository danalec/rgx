    /// UTF-7: the failure paths, and what each of them costs the stream.
    ///
    /// The oracle raises `UnicodeDecodeError` on every one of these, so the
    /// expected value here is the documented behaviour of this decoder and
    /// not the reference's.
    #[test]
    fn utf7_a_broken_stream_is_a_replacement_and_the_stream_goes_on() {
        // A `+` followed by a character that is not in the base64 alphabet:
        // one replacement for the `+`, and the character is read again.
        assert_eq!(utf8(&decode(Charset::Utf7, b"a+*b")), "a\u{FFFD}*b");
        // A section that holds no whole character: one replacement for the
        // whole section, and the bytes of the section are consumed.
        assert_eq!(utf8(&decode(Charset::Utf7, b"a+b")), "a\u{FFFD}");
        // A section whose discarded bits are not zero: one replacement for
        // the section, and the character that ended it is read again.
        assert_eq!(utf8(&decode(Charset::Utf7, b"+ab*c-")), "\u{FFFD}*c-");
        // An unterminated section at the end of the stream: one
        // replacement for the section.
        assert_eq!(utf8(&decode(Charset::Utf7, b"abc+def")), "abc\u{FFFD}");
        // A byte above 0x7F: UTF-7 is a 7-bit encoding.
        assert_eq!(utf8(&decode(Charset::Utf7, b"a\x80b")), "a\u{FFFD}b");
        // A `+` at the very end of the stream: an unterminated section
        // with no character in it. Python's `utf_7` drops it silently;
        // here it is one replacement, like every other broken section.
        assert_eq!(utf8(&decode(Charset::Utf7, b"abc+")), "abc\u{FFFD}");
    }


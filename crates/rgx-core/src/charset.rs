    /// ISO-2022-JP: the plain text the encoding starts in.
    ///
    /// The oracle: `b"Hello, world!".decode("iso2022_jp")`.
    #[test]
    fn iso2022_jp_reads_the_plain_text_it_starts_in() {
        let out = utf8(&decode(Charset::Iso2022Jp, b"Hello, world!"));
        assert_eq!(out, "Hello, world!");
    }

    /// ISO-2022-JP: every designation the encoding uses.
    ///
    /// The oracle is Python's own decoder for each one:
    /// `b"\x1b(BABC".decode("iso2022_jp")` is "ABC",
    /// `b"\x1b(J\x5c\x7e".decode("iso2022_jp")` is the yen sign and the
    /// overline, `b"\x1b$B$\x33".decode("iso2022_jp")` is the kanji, and
    /// `b"\x1b$(D\"\x2f".decode("iso2022_jp_2")` is the JIS X 0212
    /// character. The katakana set is the one Python's ISO-2022-JP codecs
    /// do not read at all, so its oracle is the same set in EUC-JP:
    /// `bytes([0x8E, 0xA1]).decode("euc_jp")` is U+FF61.
    #[test]
    fn iso2022_jp_reads_each_designation() {
        // ESC ( B: plain ASCII.
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"\x1b(BABC")), "ABC");
        // ESC ( J: the Roman set, where the backslash is the yen sign and
        // the tilde is the overline (RFC 1468 section 2).
        assert_eq!(
            utf8(&decode(Charset::Iso2022Jp, b"\x1b(J\x5c\x7e")),
            "\u{00A5}\u{203E}"
        );
        // ESC ( I: the katakana set, one byte per character.
        assert_eq!(
            utf8(&decode(Charset::Iso2022Jp, b"\x1b(I\x21\x22\x5f")),
            "\u{FF61}\u{FF62}\u{FF9F}"
        );
        // ESC $ B and ESC $ @: JIS X 0208, two bytes per character. The
        // two revisions of the set read with the same table.
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"\x1b$B$\x33")), "こ");
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"\x1b$@$\x33")), "こ");
        // ESC $ ( D: JIS X 0212, the supplementary set.
        assert_eq!(
            utf8(&decode(Charset::Iso2022Jp, b"\x1b$(D\"\x2f")),
            "\u{02D8}"
        );
    }

    /// ISO-2022-JP: the set changes in the middle of the stream.
    ///
    /// The oracle: `b"\x1b$B\x46\x7c\x4b\x5c\x1b(Bok".decode("iso2022_jp")`
    /// is "日本ok".
    #[test]
    fn iso2022_jp_switches_set_in_the_middle_of_the_stream() {
        let out = utf8(&decode(
            Charset::Iso2022Jp,
            b"\x1b$B\x46\x7c\x4b\x5c\x1b(Bok",
        ));
        assert_eq!(out, "日本ok");
    }

    /// ISO-2022-JP: the `SO` shift to the katakana set and the `SI` shift
    /// back.
    ///
    /// The oracle for the katakana is EUC-JP's SS2 form of the same set,
    /// `bytes([0x8E, 0xA1]).decode("euc_jp")`. Python's `iso2022_jp` passes
    /// `SO` and `SI` through as the control characters they are, so it
    /// reads this stream wrongly: RFC 1468 section 3 forbids both as
    /// characters in an ISO-2022-JP stream.
    #[test]
    fn iso2022_jp_shifts_to_the_katakana_set_and_back() {
        // ESC ( J puts the stream in the Roman set, SO shifts to the
        // katakana set and SI shifts back to the Roman one.
        let out = utf8(&decode(Charset::Iso2022Jp, b"\x1b(J\x0e\x21\x22\x0f!"));
        assert_eq!(out, "\u{FF61}\u{FF62}!");
    }

    /// ISO-2022-JP: the failure paths, and what each of them costs the
    /// stream.
    ///
    /// The oracle raises `UnicodeDecodeError` on every one of these, so the
    /// expected value here is the documented behaviour of this decoder and
    /// not the reference's.
    #[test]
    fn iso2022_jp_a_broken_stream_is_a_replacement_and_the_stream_goes_on() {
        // An escape that names no designation: one replacement for the
        // escape and the bytes that were read to decide it, and the bytes
        // after that are read again.
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"a\x1b(Zb")), "a\u{FFFD}b");
        // A byte that is not a character in the set that is current.
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"a\x80b")), "a\u{FFFD}b");
        // A lead byte with no trail byte: one replacement for the lead.
        assert_eq!(utf8(&decode(Charset::Iso2022Jp, b"\x1b$B$")), "\u{FFFD}");
        // A lead byte whose second byte is not a trail byte: one
        // replacement for the lead, and the byte after it is read again.
        assert_eq!(
            utf8(&decode(Charset::Iso2022Jp, b"\x1b$B$\x20")),
            "\u{FFFD}\u{FFFD}"
        );
        // A pair the table does not map: one replacement, and both bytes
        // are consumed, because the pair is one character position.
        assert_eq!(
            utf8(&decode(Charset::Iso2022Jp, b"\x1b$B$\x7c")),
            "\u{FFFD}"
        );
    }

    /// UTF-7: the shifted section.
    ///
    /// The oracle is Python's `utf_7` codec, and the first two are the
    /// examples of RFC 2152 section 5: `b"A+ImIDkQ.".decode("utf_7")` is
    /// "A≢Α." and `b"Hi Mom -+Jjo--!".decode("utf_7")` is "Hi Mom -☺-!".
    #[test]
    fn utf7_reads_a_shifted_section() {
        assert_eq!(
            utf8(&decode(Charset::Utf7, b"A+ImIDkQ.")),
            "A\u{2262}\u{0391}."
        );
        assert_eq!(
            utf8(&decode(Charset::Utf7, b"Hi Mom -+Jjo--!")),
            "Hi Mom -\u{263A}-!"
        );
        // Three kanji.
        assert_eq!(utf8(&decode(Charset::Utf7, b"+ZeVnLIqe-")), "日本語");
        // The characters that are written as themselves, around one that is
        // not: `b"Item 3 is +AKM-1.".decode("utf_7")` is "Item 3 is £1."
        assert_eq!(
            utf8(&decode(Charset::Utf7, b"Item 3 is +AKM-1.")),
            "Item 3 is \u{00A3}1."
        );
    }

